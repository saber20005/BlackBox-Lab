test('network isolation requires Host-only AND Snapshot, and reconnections invalidate scan',()=>{
 let s=createBbMission();
 assert.equal(s.adapter,'nat');
 assert.equal(bbMissionReady(s),false);
 s=bbConfigureAdapter(s,'bridged');
 assert.equal(bbMissionReady(s),false);
 s=bbConfigureAdapter(s,'host-only');
 assert.equal(bbMissionReady(s),false);
 s=bbToggleSnapshot(s,true);
 assert.equal(bbMissionReady(s),true);
 assert.equal(bbMissionScore(s),1);
 s=bbSimulateCommand(s,BB_DEMO_COMMAND);
 assert.equal(s.scanned,true);
 assert.equal(bbMissionScore(s),2);
 s=bbConfigureAdapter(s,'bridged');
 assert.equal(s.scanned,false,'changing network invalidates simulated scan');
 assert.deepEqual(s.evidence,[]);
 assert.equal(bbMissionScore(s),0);
});
