/** Unknown routes never inherit values from Object.prototype. */
export function getStageHints(trackId, stageIndex) {
  if (typeof trackId !== 'string' || !Number.isInteger(stageIndex) || stageIndex < 0) return null;
  return hintMap.get(`${trackId}-${stageIndex}`) ?? null;
}

export function createHintViewState() { return { revealed: 0 }; }

let nextHintId = 0;

/** Ephemeral guidance only; the caller owns attempt detection and scope resets. */
export function mountTrainingHints(container, { trackId, stageIndex, viewState = createHintViewState(), attempted = false } = {}) {
  const document = container.ownerDocument;
  const hints = getStageHints(trackId, stageIndex);
  if (!hints) {
    container.textContent = 'لا توجد تلميحات لهذه المرحلة.';
    return { dispose() {}, setAttempted() {} };
  }
  let disposed = false;
  let hasAttempt = Boolean(attempted);
  if (!Number.isInteger(viewState.revealed)) viewState.revealed = 0;
  viewState.revealed = Math.max(0, Math.min(hasAttempt ? 3 : 2, viewState.revealed));
  const element = (tag, text, className) => {
    const node = document.createElement(tag);
    if (text !== undefined) node.textContent = text;
    if (className) node.className = className;
    return node;
  };
  const section = element('section', undefined, 'training-hints');
  const title = element('h2', 'تلميحات تساعدك على المحاولة');
  title.id = `training-hints-title-${++nextHintId}`;
  section.setAttribute('aria-labelledby', title.id);
  const intro = element('p', 'ابدأ بقراءة المهمة والأدلة، ثم افتح التلميحات عند الحاجة. دوّن ملاحظة أو نتيجة من محاولتك لتتمكن من عرض المراجعة.');
  const list = element('div', undefined, 'training-hint-list');
  list.setAttribute('role', 'region');
  list.setAttribute('aria-label', 'التلميحات التي اخترت عرضها');
  const status = element('p', '', 'training-hint-status');
  status.setAttribute('role', 'status'); status.setAttribute('aria-live', 'polite');
  const actions = element('div', undefined, 'training-hint-actions');
  const next = element('button', '', 'secondary');
  next.type = 'button'; next.dataset.hintNext = '';
  const review = element('button', '', 'secondary');
  review.type = 'button'; review.dataset.hintReview = '';
  actions.append(next, review);
  section.append(title, intro, list, actions, status);
  container.replaceChildren(section);

  function render() {
    if (disposed) return;
    list.replaceChildren();
    const names = ['التلميح الأول', 'توجيه أدق', 'مراجعة بعد المحاولة'];
    // Review text is not added to the DOM until its explicit reveal action.
    for (let index = 0; index < viewState.revealed; index++) {
      const card = element('article', undefined, 'training-hint-card');
      card.dataset.hintLevel = String(index + 1);
      card.append(element('h3', names[index]), element('p', hints[index]));
      list.append(card);
    }
    next.textContent = viewState.revealed === 0 ? 'إظهار التلميح الأول' : viewState.revealed === 1 ? 'إظهار التوجيه الأدق' : 'إخفاء التلميحات';
    review.disabled = !hasAttempt || viewState.revealed < 2;
    review.textContent = viewState.revealed === 3 ? 'إخفاء المراجعة' : 'عرض المراجعة بعد المحاولة';
    status.textContent = viewState.revealed === 3 ? 'قارن المراجعة بما دوّنته وبالدليل الأصلي. عرضها لا يؤكد إكمال المرحلة.'
      : !hasAttempt ? 'لإتاحة المراجعة، دوّن أولًا ملاحظة أو نتيجة من محاولتك في حقول المرحلة.'
        : viewState.revealed < 2 ? 'دوّنت محاولتك؛ افتح التلميحين بالتتابع ثم اختر عرض المراجعة عند الحاجة.'
          : 'يمكنك الآن اختيار عرض المراجعة ومقارنتها بمحاولتك.';
  }
  next.addEventListener('click', () => {
    if (disposed) return;
    viewState.revealed = viewState.revealed >= 2 ? 0 : viewState.revealed + 1;
    render();
  });
  review.addEventListener('click', () => {
    if (disposed || !hasAttempt || viewState.revealed < 2) return;
    viewState.revealed = viewState.revealed === 3 ? 2 : 3;
    render();
  });
  render();
  return {
    dispose() { disposed = true; },
    setAttempted(value) {
      const nextValue = Boolean(value);
      if (disposed || nextValue === hasAttempt) return;
      hasAttempt = nextValue;
      if (!hasAttempt && viewState.revealed === 3) viewState.revealed = 2;
      render();
    },
  };
}
